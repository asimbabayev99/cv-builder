export function getTranslations(language: SupportedLanguage): TemplateTranslations {
  return translations[language] || translations.en;
}

export function formatDate(dateStr: string | undefined, language: SupportedLanguage): string {
  if (!dateStr) return '';

  try {
    const date = new Date(dateStr);
    const options: Intl.DateTimeFormatOptions = { month: '2-digit', year: 'numeric' };

    // Map language codes to locale codes
    const localeMap: Record<SupportedLanguage, string> = {
      en: 'en-GB',
      de: 'de-DE',
      fr: 'fr-FR',
      es: 'es-ES',
      it: 'it-IT',
      pt: 'pt-PT',
      ru: 'ru-RU',
      ar: 'ar-SA',
      zh: 'zh-CN',
      ja: 'ja-JP',
      ko: 'ko-KR',
      az: 'az-AZ',
    };

    return date.toLocaleDateString(localeMap[language] || 'en-GB', options);
  } catch {
    return dateStr;
  }
}

export function isRTL(language: SupportedLanguage): boolean {
  return language === 'ar';
}
